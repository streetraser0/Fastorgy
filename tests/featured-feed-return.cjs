const assert=require('node:assert/strict');
const {boot}=require('./helpers/category-seller-harness.cjs');
const h=boot({noMedia:true});
h.run('cars=cars.slice(0,80);ends.splice(0,ends.length,...cars.map(lot=>Date.parse(lot.ends)));invalidateSubscriptionInventory();$("#advanced-reset").onclick();catalogLimit=60;render();');
const view=h.context.window,page={scrollTop:880,scrollLeft:12},scrolls=[];
h.context.document.scrollingElement=page;view.scrollY=880;view.scrollX=12;
view.scrollTo=value=>{scrolls.push(value);view.scrollY=value.top;view.scrollX=value.left;page.scrollTop=value.top;page.scrollLeft=value.left};
h.node('#featured-track').scrollLeft=215;h.node('#grid').scrollTop=350;
assert.equal(h.run('window.FasOpenFeaturedFeed({mode:"nearby",ids:cars.map(lot=>lot.id)})'),true);
assert.equal(h.run('reelsMode'),true);assert.equal(h.run('catalogLimit'),24);
assert.equal(h.run('setReels.returnPosition.limit'),60,'the already mounted catalogue count survives the feed entry resetting its limit');
view.scrollY=0;page.scrollTop=0;h.node('#featured-track').scrollLeft=999;
h.run('setReels(false)');
assert.equal(h.run('reelsMode'),false);assert.equal(view.scrollY,880);assert.equal(view.scrollX,12);
assert.equal(h.node('#featured-track').scrollLeft,215);assert.equal(h.node('#grid').scrollTop,350);
assert.equal(h.run('catalogLimit'),60);assert.equal(h.run('setReels.returnPosition'),null);
assert.equal(scrolls.length,1,'return restores once without a delayed frame that can override a new navigation');
h.run('saved=cars.slice(0,20).map(lot=>lot.id);tab="fav";$("#sort").value="high";$("#adv-price-min").value="1";catalogLimit=40;render();');
const priorIds=Array.from(h.run('visibleLots.map(lot=>lot.id)'));
h.run('window.FasOpenFeaturedFeed({mode:"ending",ids:cars.map(lot=>lot.id)});setReels(false);');
assert.equal(h.run('tab'),'fav');assert.equal(h.node('#sort').value,'high');
assert.equal(h.node('#adv-price-min').value,'1');assert.equal(h.run('catalogLimit'),40);
assert.deepEqual(Array.from(h.run('visibleLots.map(lot=>lot.id)')),priorIds,'return restores the actual source subset and order, not only its pixel position');
h.run('window.FasFeaturedLots={orderLots:()=>[]};window.FasOpenFeaturedFeed({mode:"ending",ids:cars.map(lot=>lot.id)});render();');
assert.equal(h.run('visibleLots.length'),0,'an expired strict featured selection never falls back to unrelated inventory');
assert.equal(h.run('recommendationSession.strict'),true);
console.log('PASS: actual featured feed entry restores page, horizontal track, catalogue scroll and loaded count; empty strict scopes remain empty.');
