import { readFile, writeFile, readdir, mkdir, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const sharp = require(path.join(root, 'mobile/node_modules/sharp'));
sharp.concurrency(2);
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const originals = JSON.parse(await readFile(path.join(root, 'tests/fixtures/photo-original-sha256.json'), 'utf8'));
const directory = path.join(root, 'dist/assets/photos/responsive');
await mkdir(directory, { recursive: true });
const images = {}, generated = new Set();
let previewBytes = 0;
for (const [name, expectedHash] of Object.entries(originals)) {
  const originalSrc = 'assets/photos/' + name, file = path.join(root, 'dist', originalSrc);
  const original = await readFile(file);
  if (digest(original) !== expectedHash) throw Error('Original photo changed; review its identity before deriving previews: ' + name);
  const metadata = await sharp(original).metadata();
  if (!metadata.width || !metadata.height || ![undefined, 1].includes(metadata.orientation)) throw Error('Review photo orientation: ' + name);
  const variants = [];
  for (const width of [...new Set([480, 960].map(value => Math.min(value, metadata.width)))]) {
    const { data, info } = await sharp(original).resize({ width, withoutEnlargement: true }).webp({ quality: 82, effort: 4 }).toBuffer({ resolveWithObject: true });
    const filename = name.replace(/\.jpg$/i, '') + '-' + info.width + '-' + digest(data).slice(0, 12) + '.webp';
    await writeFile(path.join(directory, filename), data);
    generated.add(filename);previewBytes += data.length;
    variants.push({ src: 'assets/photos/responsive/' + filename, width: info.width });
  }
  const srcset = variants.map(item => item.src + ' ' + item.width + 'w').join(', ');
  const full = [...variants];
  if (!full.some(item => item.width === metadata.width)) full.push({ src: originalSrc, width: metadata.width });
  images[originalSrc] = { src: variants[0].src, srcset, fullSrcset: full.map(item => item.src + ' ' + item.width + 'w').join(', '), originalSrc, width: metadata.width, height: metadata.height };
  if (digest(await readFile(file)) !== expectedHash) throw Error('Original photo changed during generation: ' + name);
}
for (const name of await readdir(directory)) if (/^[a-z0-9-]+-\d+-[a-f0-9]{12}\.webp$/.test(name) && !generated.has(name)) await unlink(path.join(directory, name));

const helper = String.raw`/* Generated by scripts/generate-responsive-media.mjs. Previews only; originals remain untouched. */
(()=>{
 'use strict';
 const images=${JSON.stringify(images)};
 for(const value of Object.values(images))Object.freeze(value);
 function image(value){
  if(typeof value!=='string'||!value||value!==value.trim()||!/^\/?assets\/photos\/[a-z0-9-]+\.jpg(?:[?][^#]*)?$/.test(value))return null;
  const [pathname,query='']=value.split('?');
  if(query){const params=new URLSearchParams(query);for(const [key,item]of params)if(key!=='view'||!/^\d+$/.test(item))return null}
  return images[pathname.replace(/^\//,'')]||null;
 }
 function original(value){return image(value)?.originalSrc??value}
 const api=Object.freeze({image,original});globalThis.FasResponsiveMedia=api;if(typeof window!=='undefined')window.FasResponsiveMedia=api;
})();
`;
await writeFile(path.join(root, 'dist/responsive-media.js'), helper);

// Brand artwork has its own deterministic vector generator. Photo optimization
// must not resize or rewrite the approved centered lockup.
const logoFile = path.join(root, 'dist/assets/brand/fas-torgi-logo.png');
const logoResult = await readFile(logoFile);
console.log(JSON.stringify({ originalsUnchanged: Object.keys(originals).length, previews: generated.size, previewBytes, helperBytes: Buffer.byteLength(helper), logoBytes: logoResult.length, logoWidth: (await sharp(logoResult).metadata()).width }));
