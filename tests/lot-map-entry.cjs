const assert=require('assert/strict');
const {boot}=require('./helpers/category-seller-harness.cjs');
const h=boot({noMedia:true});
const lot=h.run('cars.find(item=>isLotLive(item)&&lotLocation(item))');
assert(lot,'available located lot exists');
let opened=[];
h.context.window.FasPropertyMap={openLotLocation(id){opened.push(id);return true}};
const html=h.run(`cardHTML(cars.find(item=>item.id===${lot.id}))`);
assert(html.includes(`data-open-lot-map="${lot.id}"`),'feed city is a map action');
assert(html.includes('Открыть местоположение лота на карте:'),'map action has an accessible name');
const location=html.match(/<div class="location">([\s\S]*?)<\/div>/)[1];
const mapButton=location.match(/<button[^>]+data-open-lot-map[^>]*>([\s\S]*?)<\/button>/)[1];
assert(!mapButton.includes('<button'),'distance setup is not nested in the map button');
h.run(`openCar(${lot.id})`);
const modal=h.node('#modal'),content=h.node('#modal-content');
assert(content.innerHTML.includes(`<div class="purchase-location"><button type="button" class="lot-map-link" data-open-lot-map="${lot.id}"`),'lot detail city opens the same map action');
modal.scrollTop=420;
let prevented=false,stopped=false;
const button={dataset:{openLotMap:String(lot.id)}};
const target={closest(selector){return selector==='[data-open-lot-map]'?button:null}};
h.dispatchClick({target,preventDefault(){prevented=true},stopPropagation(){stopped=true}});
assert.deepEqual(opened,[lot.id],'clicking city delegates the selected canonical lot to the map');
assert(prevented&&stopped,'map click does not trigger parent lot navigation');
assert.equal(modal.open,true,'lot stays open beneath map');
assert.equal(modal.scrollTop,420,'opening location does not reset lot scroll');
const before=h.run('JSON.stringify({userRegion,userGeo})');
assert.equal(h.run(`openLotMap(${lot.id})`),true);
assert.equal(h.run('JSON.stringify({userRegion,userGeo})'),before,'opening object location never changes user origin');
opened=[];
for(const value of ['0','-1','1.5','NaN','9007199254740992','999999999'])assert.equal(h.run(`openLotMap(${value})`),false);
assert.deepEqual(opened,[],'invalid or missing lots are never delegated');
h.run(`cars.find(item=>item.id===${lot.id}).status='paused'`);
assert.equal(h.run(`openLotMap(${lot.id})`),false);
assert.deepEqual(opened,[],'withdrawn lot cannot open stale map');
h.run(`cars.find(item=>item.id===${lot.id}).status='live'`);
h.context.window.FasPropertyMap=undefined;
assert.equal(h.run(`openLotMap(${lot.id})`),false,'missing map module fails safely');
assert.equal(modal.scrollTop,420,'missing module keeps the card position');
console.log('Lot location entry: feed/detail city action, delegation, scroll/origin preservation, and stale/invalid guards passed');
