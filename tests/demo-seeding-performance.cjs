const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context=vm.createContext({Date,console});
for(const file of ['category-tree.js','demo-profiles.js','catalog-data.js'])vm.runInContext(fs.readFileSync('dist/'+file,'utf8'),context);
let inspected=0;
const list=Array.from({length:10000},(_,index)=>{const lot={id:20000000+index};Object.defineProperty(lot,'demoVehicleSample',{enumerable:true,get(){inspected++;return undefined}});return lot});
const existing={id:9000000,demoVehicleSample:'sitrak-c7h',regionCode:'77',demo:true,demoEdited:true,name:'Мой сохранённый тягач',price:7654321,ends:'2020-01-01T00:00:00.000Z'};
list.push(existing);const snapshot=JSON.stringify(existing);
context.list=list;
vm.runInContext('seedCommercialDemoLots(list,Date.now())',context);
const regions=Array.from(vm.runInContext('RF_REGIONS',context));
assert.equal(list.length,10000+2*regions.length,'an existing commercial sample fills its regional slot');
assert.equal(JSON.stringify(existing),snapshot,'completion preserves edited sample fields and deadline');
assert(inspected<=10000*2,'commercial completion inspects each input row a bounded number of times, rather than rescanning it for every region');
const counts=new Map();for(const lot of list)if(lot.demoVehicleSample==='sitrak-c7h')counts.set(lot.regionCode,(counts.get(lot.regionCode)||0)+1);
for(const region of regions)assert.equal(counts.get(region.code),1);
const ids=list.map(lot=>lot.id).join(',');inspected=0;
vm.runInContext('seedCommercialDemoLots(list,Date.now())',context);
assert.equal(list.map(lot=>lot.id).join(','),ids,'repeated completion creates no duplicate IDs');
assert(inspected<=10000*2,'an already complete catalogue also stays linear');
assert.equal(JSON.stringify(existing),snapshot);
console.log('PASS: commercial demo completion is linear in existing inventory, preserves edited regional samples and remains idempotent.');
